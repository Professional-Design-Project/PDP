"use client";

import { useEffect, useRef } from "react";

type LeavePanelProps = {
  onLeave: (withFeedback: boolean) => void;
  onStay: () => void;
};

export function LeavePanel({ onLeave, onStay }: LeavePanelProps) {
  const firstRef = useRef<HTMLButtonElement>(null);

  useEffect(() => {
    firstRef.current?.focus();
  }, []);

  return (
    <div className="absolute inset-0 z-20 flex animate-fade items-end bg-ink/70 sm:items-center sm:justify-center">
      <section
        aria-labelledby="leave-title"
        className="w-full animate-panel bg-canvas p-6 text-ink sm:max-w-lg sm:p-8"
      >
        <h2 id="leave-title" className="text-[32px] leading-none font-bold tracking-[-0.03em]">
          Leave the room?
        </h2>
        <p className="mt-3 leading-relaxed text-ink/80">
          The interviewer can read your transcript back and leave a few notes on what went well and
          what to work on. It is generated by AI from the words only, so it may contain mistakes.
        </p>
        <div className="mt-6 grid gap-3">
          <button
            ref={firstRef}
            type="button"
            onClick={() => onLeave(true)}
            className="h-14 bg-cobalt px-5 text-left text-lg font-semibold text-white hover:bg-cobalt/90 focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-ink"
          >
            Leave and get feedback
          </button>
          <button
            type="button"
            onClick={() => onLeave(false)}
            className="h-14 border border-ink px-5 text-left text-lg font-semibold hover:bg-ink hover:text-white focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-cobalt"
          >
            Leave without feedback
          </button>
          <button
            type="button"
            onClick={onStay}
            className="h-12 justify-self-start px-1 font-semibold underline underline-offset-4 hover:text-cobalt focus-visible:outline-2 focus-visible:outline-cobalt"
          >
            Keep talking
          </button>
        </div>
      </section>
    </div>
  );
}
